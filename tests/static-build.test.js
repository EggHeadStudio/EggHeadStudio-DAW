import test from 'node:test';
import assert from 'node:assert/strict';
import {mkdtemp,readFile,rm,writeFile,mkdir} from 'node:fs/promises';
import {join} from 'node:path';
import {tmpdir} from 'node:os';
import {buildStatic} from '../scripts/build-static.mjs';

test('static deployment versions the entire module, Worker, Worklet, vendor and CSS namespace deterministically',async()=>{
 const temporary=await mkdtemp(join(tmpdir(),'ehs-static-test-'));
 try{
  const source=join(temporary,'source'),output=join(temporary,'output');
  await Promise.all(['src','vendor','icons','scripts'].map(directory=>mkdir(join(source,directory),{recursive:true})));
  await writeFile(join(source,'index.html'),'<html><head><link rel="manifest" href="./manifest.webmanifest"><link rel="apple-touch-icon" href="./icons/apple-touch-icon.png"><link href="./src/style.css"></head><script src="./src/app.js"></script></html>');
  const iconNames=['icon-192.png','icon-512.png','icon-maskable-512.png','apple-touch-icon.png','icon-1024.png'];
  const manifestNames=['icon-192.png','icon-512.png','icon-maskable-512.png','icon-1024.png'];
  const manifest={name:'EggHeadStudio DAW',short_name:'EggHeadStudio',start_url:'./',scope:'./',display:'standalone',theme_color:'#10131b',icons:manifestNames.map((name,index)=>({src:`./icons/${name}`,sizes:`${[192,512,512,1024][index]}x${[192,512,512,1024][index]}`,type:'image/png',purpose:index===2?'maskable':'any'}))};
  await writeFile(join(source,'manifest.webmanifest'),JSON.stringify(manifest));
  await writeFile(join(source,'scripts','service-worker-template.js'),"const CACHE_NAME = 'ehs-shell-__EHS_BUILD_VERSION__'; const BUILD_VERSION = '__EHS_BUILD_VERSION__'; const SHELL_URLS = __EHS_SHELL_URLS__; self.addEventListener('message',event=>{if(event.data?.type==='EHS_ACTIVATE_IF_SAFE')return});");
  for(const name of iconNames)await writeFile(join(source,'icons',name),`icon:${name}`);
  const sources={'app.js':"import './audio.js';new Worker(new URL('./worker.js',import.meta.url));",'audio.js':"import '../vendor/dsp.js';",'worker.js':'postMessage(1);','style.css':'body{color:red}'};
  for(const[name,content]of Object.entries(sources))await writeFile(join(source,'src',name),content);
  await writeFile(join(source,'vendor','dsp.js'),'export const quality=4;');
  const first=await buildStatic({source,output}),again=await buildStatic({source,output});
  assert.equal(first.version,again.version);
  const html=await readFile(join(output,'index.html'),'utf8');
  assert.ok(html.includes(`./assets/${first.version}/src/app.js`));
  assert.ok(html.includes(`./assets/${first.version}/src/style.css`));
  assert.ok(html.includes('href="./manifest.webmanifest"'));
  assert.ok(html.includes(`name="ehs-build" content="${first.version}"`));
  const url=new URL(`./assets/${first.version}/src/app.js`,'https://example.test/repository/');
  assert.equal(new URL('../vendor/dsp.js',url).pathname,`/repository/assets/${first.version}/vendor/dsp.js`);
  assert.equal(await readFile(join(output,'assets',first.version,'src','worker.js'),'utf8'),sources['worker.js']);
  const serviceWorker=await readFile(join(output,'service-worker.js'),'utf8');
  assert.ok(serviceWorker.includes(`ehs-shell-${first.version}`));
  assert.ok(serviceWorker.includes(`const BUILD_VERSION = '${first.version}'`));
  assert.ok(serviceWorker.includes('EHS_ACTIVATE_IF_SAFE'));
  assert.ok(!serviceWorker.includes('clients.claim'));
  assert.ok(!serviceWorker.includes('__EHS_'));
  for(const name of iconNames)assert.ok(serviceWorker.includes(`./icons/${name}`));
  assert.ok(serviceWorker.includes(`./assets/${first.version}/src/app.js`));
  assert.ok(serviceWorker.includes(`./assets/${first.version}/vendor/dsp.js`));
  assert.equal(await readFile(join(output,'icons','icon-maskable-512.png'),'utf8'),'icon:icon-maskable-512.png');
  assert.deepEqual(JSON.parse(await readFile(join(output,'manifest.webmanifest'),'utf8')),manifest);
  await writeFile(join(source,'vendor','dsp.js'),'export const quality=8;');
  const changed=await buildStatic({source,output});
  assert.notEqual(changed.version,first.version);
  assert.equal(await readFile(join(output,'assets',first.version,'vendor','dsp.js'),'utf8'),'export const quality=4;');
  assert.deepEqual(JSON.parse(await readFile(join(output,'version.json'),'utf8')),{version:changed.version});
 }finally{await rm(temporary,{recursive:true,force:true})}
});
